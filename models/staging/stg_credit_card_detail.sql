select
    cast(card_account_id as string)            as card_account_id,
    cast(customer_id as string)                as customer_id,
    cast(card_type as string)                  as card_type,
    cast(card_network as string)               as card_network,
    cast(card_number_masked as string)         as card_number_masked,
    cast(card_status as string)                as card_status,
    cast(credit_limit as double)               as credit_limit,
    cast(available_credit as double)           as available_credit,
    cast(current_outstanding as double)        as current_outstanding,
    cast(current_cycle_balance as double)      as current_cycle_balance,
    cast(next_cycle_balance as double)         as next_cycle_balance,
    cast(statement_day as int)                 as statement_day,
    cast(payment_due_day as int)               as payment_due_day,
    cast(last_statement_balance as double)     as last_statement_balance,
    cast(last_statement_date as date)          as last_statement_date,
    cast(min_amount_due as double)             as min_amount_due,
    cast(total_amount_due as double)           as total_amount_due,
    cast(last_payment_date as date)            as last_payment_date,
    cast(last_payment_amount as double)        as last_payment_amount,
    cast(payment_behavior as string)           as payment_behavior,
    cast(utilization_ratio as double)          as utilization_ratio,
    cast(reward_points as int)                 as reward_points,
    cast(is_overlimit as boolean)              as is_overlimit,
    cast(overlimit_count_lifetime as int)      as overlimit_count_lifetime,
    cast(revolving_balance as double)          as revolving_balance,
    cast(card_issue_date as date)              as card_issue_date,
    cast(card_expiry_date as date)             as card_expiry_date,
    cast(international_enabled as boolean)     as international_enabled,
    cast(contactless_enabled as boolean)       as contactless_enabled,
    cast(revolving_apr as double)              as revolving_apr,
    cast(created_at as timestamp)              as created_at,
    cast(updated_at as timestamp)              as updated_at
from {{ source('bronze', 'credit_card_detail') }}