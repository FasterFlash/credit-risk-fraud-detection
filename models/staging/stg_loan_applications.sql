-- stg_loan_applications.sql
select
    cast(application_id as string)             as application_id,
    cast(customer_id as string)                as customer_id,
    cast(co_applicant_id as string)             as co_applicant_id,
    cast(loan_type as string)                  as loan_type,
    cast(product_code as string)               as product_code,
    cast(applied_amount as double)             as applied_amount,
    cast(applied_tenure_months as int)         as applied_tenure_months,
    cast(purpose as string)                    as purpose,
    cast(application_channel as string)        as application_channel,
    cast(application_date as date)             as application_date,
    cast(application_timestamp as timestamp)   as application_timestamp,
    cast(status as string)                     as status,
    cast(declared_monthly_income as double)    as declared_monthly_income,
    cast(existing_emi_obligations as double)   as existing_emi_obligations,
    cast(foir_at_application as double)        as foir_at_application,
    cast(property_city as string)              as property_city,
    cast(property_type as string)              as property_type,
    cast(vehicle_category as string)           as vehicle_category,
    cast(vehicle_make as string)               as vehicle_make,
    cast(vehicle_model as string)              as vehicle_model,
    cast(is_new_vehicle as boolean)            as is_new_vehicle,
    cast(rejection_reason as string)           as rejection_reason,
    cast(processing_fee_waived as boolean)     as processing_fee_waived,
    cast(referral_code as string)              as referral_code,
    cast(created_at as timestamp)              as created_at,
    cast(updated_at as timestamp)              as updated_at
from {{ source('bronze', 'loan_applications') }}