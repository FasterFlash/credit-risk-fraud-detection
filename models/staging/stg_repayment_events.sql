select
    cast(repayment_event_id as string)         as repayment_event_id,
    cast(loan_account_id as string)            as loan_account_id,
    cast(schedule_id as string)                as schedule_id,
    cast(customer_id as string)                as customer_id,
    cast(installment_number as int)            as installment_number,
    cast(due_date as date)                     as due_date,
    cast(amount_due as double)                 as amount_due,
    cast(payment_date as date)                 as payment_date,
    cast(amount_paid as double)                as amount_paid,
    cast(shortfall as double)                  as shortfall,
    cast(is_partial as boolean)                as is_partial,
    cast(is_missed as boolean)                 as is_missed,
    cast(is_on_time as boolean)                as is_on_time,
    cast(within_grace_period as boolean)       as within_grace_period,
    cast(days_late as int)                     as days_late,
    cast(payment_mode as string)               as payment_mode,
    cast(payment_reference as string)          as payment_reference,
    cast(nach_presented as boolean)            as nach_presented,
    cast(nach_return_reason as string)         as nach_return_reason,
    cast(grace_period_used as boolean)         as grace_period_used,
    cast(penalty_charged as double)            as penalty_charged,
    cast(penal_interest_rate as double)        as penal_interest_rate,
    cast(dpd_at_event as int)                  as dpd_at_event,
    cast(loan_status_at_event as string)       as loan_status_at_event,
    cast(consecutive_missed_at_event as int)   as consecutive_missed_at_event,
    cast(salary_credited_this_month as boolean) as salary_credited_this_month,
    cast(created_at as timestamp)              as created_at
from {{ source('bronze', 'repayment_events') }}