select
    cast(customer_id as string)            as customer_id,
    cast(full_name as string)              as full_name,
    cast(date_of_birth as date)            as date_of_birth,
    cast(gender as string)                 as gender,
    cast(pan_number as string)             as pan_number,
    cast(aadhaar_last4 as string)          as aadhaar_last4,
    cast(mobile_number as string)          as mobile_number,
    cast(email as string)                  as email,
    cast(address_line1 as string)          as address_line1,
    cast(address_line2 as string)          as address_line2,
    cast(city as string)                   as city,
    cast(state as string)                  as state,
    cast(pin_code as string)               as pin_code,
    cast(home_branch_ifsc as string)       as home_branch_ifsc,
    cast(bank_account_number as string)    as bank_account_number,
    cast(bank_account_type as string)      as bank_account_type,
    cast(persona as string)                as persona,
    cast(employment_type as string)        as employment_type,
    cast(employer_name as string)          as employer_name,
    cast(monthly_income as double)         as monthly_income,
    cast(customer_segment as string)       as customer_segment,
    cast(kyc_status as string)             as kyc_status,
    cast(kyc_verified_date as date)        as kyc_verified_date,
    cast(is_active as boolean)             as is_active,
    cast(customer_since_date as date)      as customer_since_date,
    cast(lifecycle_status as string)       as lifecycle_status,
    cast(dormant_since_date as date)       as dormant_since_date,
    cast(created_at as timestamp)          as created_at,
    cast(updated_at as timestamp)          as updated_at
from {{ source('bronze', 'customers') }}